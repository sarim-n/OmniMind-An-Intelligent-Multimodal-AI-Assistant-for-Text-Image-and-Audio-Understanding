import React, { useState } from "react";
import { useQuery } from "@tanstack/react-query";
import { AlertTriangle, Cpu, X } from "lucide-react";
import { API_BASE_URL } from "../api/client";

interface HealthData {
  status: string;
  profile: string;
  mock_models: boolean;
  version: string;
}

export const MockBanner: React.FC = () => {
  const [dismissed, setDismissed] = useState(false);

  const { data: health } = useQuery<HealthData>({
    queryKey: ["health"],
    queryFn: async () => {
      // Backend mounts /health at root and at /api/v1/health
      const rootUrl = API_BASE_URL.replace(/\/api\/v1\/?$/, "");
      const res = await fetch(`${rootUrl}/health`);
      if (!res.ok) {
        throw new Error("Failed to check health");
      }
      return res.json();
    },
    staleTime: 60_000,
  });

  if (!health?.mock_models || dismissed) {
    return null;
  }

  return (
    <aside
      aria-label="Mock mode notice"
      className="bg-amber-500/10 border-b border-amber-500/20 text-amber-300 px-4 py-2 text-xs flex items-center justify-between transition-colors z-40"
    >
      <div className="flex items-center space-x-2">
        <AlertTriangle className="w-4 h-4 text-amber-400 shrink-0" />
        <span className="font-semibold">Mock Models Active:</span>
        <span className="text-amber-200/90">
          Inference is running in synthetic mock mode (<code className="font-mono bg-amber-500/20 px-1 py-0.5 rounded">PROFILE={health.profile}</code>, <code className="font-mono bg-amber-500/20 px-1 py-0.5 rounded">MOCK_MODELS=true</code>). Output text and analysis are generated by deterministic mocks.
        </span>
      </div>
      <div className="flex items-center space-x-3">
        <span className="hidden sm:inline-flex items-center space-x-1 text-amber-400/80 font-mono">
          <Cpu className="w-3.5 h-3.5" />
          <span>v{health.version}</span>
        </span>
        <button
          onClick={() => setDismissed(true)}
          className="text-amber-400/80 hover:text-amber-200 p-0.5 transition-colors"
          title="Dismiss warning for this session"
        >
          <X className="w-3.5 h-3.5" />
        </button>
      </div>
    </aside>
  );
};
